export type AttrValue = string | string[] | number | boolean;

export type AxisValue = {
  v: string;
  mult: number;
  /** Дополнительные атрибуты, которые задаёт это значение оси (например, ОЗУ по памяти). */
  extra?: Record<string, AttrValue>;
};

export type Axis = { key: string; values: AxisValue[] };

export type ModelSpec = {
  category: string;
  brand: string;
  name: string;
  /** Базовая цена самого дешёвого варианта, ₽. */
  base: number;
  fixed: Record<string, AttrValue>;
  axes: Axis[];
};

const colorAxis = (keys: string[]): Axis => ({
  key: "color",
  values: keys.map((v) => ({ v, mult: 1 })),
});

