const laptopModels: ModelSpec[] = laptops.map(
  ([brand, name, base, ram, storage, screen, cpu, gpu, os, colors]) => {
    // Пары ОЗУ/накопитель идут по ступеням: чем больше память, тем выше ОЗУ.
    const steps = Math.max(ram.length, storage.length);
    const configs: AxisValue[] = [];
    for (let i = 0; i < steps; i++) {
      const r = ram[Math.min(i, ram.length - 1)] as number;
      const s = storage[Math.min(i, storage.length - 1)] as number;
      if (configs.some((c) => c.v === `${r}-${s}`)) continue;
      configs.push({
        v: `${r}-${s}`,
        mult: 1 + 0.2 * i,
        extra: { ram: String(r), storage: String(s) },
      });
    }
    return {
      category: "laptops",
      brand,
      name,
      base,
      fixed: { screen, cpu, gpu, os },
      axes: [{ key: "config", values: configs }, colorAxis(colors)],
    };
  },
);

